/**
 * Generates a ready-to-use `.env.local` for local development: a fresh
 * AUTH_SECRET and one account per role with a random password. Passwords are
 * printed once to the terminal and only their scrypt hashes are written to disk.
 *
 * Usage: npm run setup:env            (refuses to overwrite an existing file)
 *        npm run setup:env -- --force (overwrite)
 */
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { ROLES, ROLE_LABELS, type Role } from '../src/lib/auth/roles';
import { hashPassword } from '../src/lib/auth/users';

const target = resolve(process.cwd(), '.env.local');
if (existsSync(target) && !process.argv.includes('--force')) {
  console.error('.env.local already exists. Re-run with --force to overwrite it.');
  process.exit(1);
}

const accounts = ROLES.map((role: Role) => {
  const password = randomBytes(12).toString('base64url');
  return { email: `${role}@vitalis.local`, role, password, passwordHash: hashPassword(password) };
});

const users = accounts.map(({ email, role, passwordHash }) => ({ email, role, passwordHash }));
const contents = [
  '# Generated by `npm run setup:env`. Local development only; never commit this file.',
  `AUTH_SECRET=${randomBytes(48).toString('base64url')}`,
  `AUTH_USERS='${JSON.stringify(users)}'`,
  'NEXT_PUBLIC_SITE_URL=http://localhost:9002',
  '# GEMINI_API_KEY=   # optional: enables live AI analysis',
  '',
].join('\n');

writeFileSync(target, contents, { mode: 0o600 });

console.log('Wrote .env.local. Local development accounts (shown once):\n');
for (const a of accounts) {
  console.log(`  ${ROLE_LABELS[a.role].padEnd(24)} ${a.email.padEnd(24)} ${a.password}`);
}
console.log('\nStart the app with `npm run dev` and sign in at http://localhost:9002/login');
